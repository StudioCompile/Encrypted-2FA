// Builds public/assets/icons.svg from Lucide (https://lucide.dev, ISC licence).
// Usage: npm i -D lucide-static && node scripts/build-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('../node_modules/lucide-static/icons/', import.meta.url);
const map = { // our id -> lucide icon
  shield: 'shield-check', file: 'file', note: 'sticky-note', image: 'image', settings: 'settings', copy: 'copy',
  edit: 'pencil', trash: 'trash-2', search: 'search', plus: 'plus', x: 'x', upload: 'upload', download: 'download',
  qr: 'qr-code', lock: 'lock', cloud: 'cloud', device: 'hard-drive', key: 'key-round', clock: 'clock', text: 'file-text'
};
let out = '<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Icons: Lucide, ISC licence. Generated by scripts/build-icons.mjs -->\n';
for (const [id, name] of Object.entries(map)) {
  const svg = readFileSync(new URL(name + '.svg', dir), 'utf8');
  const inner = svg.replace(/<!--.*?-->/s, '').replace(/^[\s\S]*?<svg[\s\S]*?>/, '').replace(/<\/svg>\s*$/, '').trim();
  out += `<symbol id="i-${id}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner.replace(/\s+/g, ' ')}</symbol>\n`;
}
writeFileSync(new URL('../public/assets/icons.svg', import.meta.url), out + '</svg>\n');
console.log('wrote public/assets/icons.svg');
